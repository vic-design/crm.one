<?php

return [
    /*
    |--------------------------------------------------------------------------
    | Default Pagination Per Page
    |--------------------------------------------------------------------------
    |
    | Здесь задается количество записей на страницу по умолчанию.
    | Значение берется из .env, fallback = 20.
    |
    */
    'default_per_page' => (int) env('PAGINATION_DEFAULT_PER_PAGE', 20),

    /*
    |--------------------------------------------------------------------------
    | Available Per Page Options
    |--------------------------------------------------------------------------
    |
    | Доступные варианты для выбора пользователем.
    | Значение берется из .env как строка "20,30,50" и преобразуется в массив.
    |
    */
    'per_page_options' => array_map(
        'intval',
        explode(',', (string) env('PAGINATION_PER_PAGE_OPTIONS', '20,30,50'))
    ),
];
